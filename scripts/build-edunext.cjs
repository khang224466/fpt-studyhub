const fs = require('node:fs');
const terser = require('next/dist/compiled/terser');

async function main() {
  const tracker = fs.readFileSync('scripts/turn-tracker.js', 'utf8');
  const client = fs.readFileSync('scripts/edunext-client.js', 'utf8').replace('function e(e, serverOrigin) {', `function e(e, serverOrigin) {\n${tracker}\n`);
  const { code } = await terser.minify(client, { compress: true, mangle: true });
  if (!code) throw new Error('Empty client bundle');
  // A single generated module serves bookmarklet, inject route and userscript.
  fs.writeFileSync('src/lib/edunextBundle.ts', `// Generated by scripts/build-edunext.cjs; edit scripts/edunext-client.js instead.\nexport const EDUNEXT_VERSION = '10.2.59';\nexport const EDUNEXT_SOURCE = ${JSON.stringify(code)};\n`);
  console.log(`Built EduNext 10.2.59 (${Buffer.byteLength(code)} bytes)`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
